// Helper: Get list of cities for a given district
export function getCitiesForDistrict(district: District): CityInfo[] {
  return SRI_LANKA_CITIES_BY_DISTRICT[district] || [];
}

// Helper: Search across all districts
export function searchAllCities(query: string): { district: District; city: CityInfo }[] {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();
  const results: { district: District; city: CityInfo }[] = [];

  (Object.keys(SRI_LANKA_CITIES_BY_DISTRICT) as District[]).forEach((d) => {
    SRI_LANKA_CITIES_BY_DISTRICT[d].forEach((c) => {
      if (c.name.toLowerCase().includes(q) || (c.postalCode && c.postalCode.includes(q))) {
        results.push({ district: d, city: c });
      }
    });
  });

  return results;
}
